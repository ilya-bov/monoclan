#!/bin/bash

# Скрипт для очистки Docker и освобождения места на сервере

echo "=== Очистка Docker ==="

# Остановить все контейнеры
echo "Остановка всех контейнеров..."
docker stop $(docker ps -aq) 2>/dev/null || true

# Удалить остановленные контейнеры
echo "Удаление остановленных контейнеров..."
docker container prune -f

# Удалить неиспользуемые образы (старые версии)
echo "Удаление неиспользуемых образов..."
docker image prune -a -f

# Удалить неиспользуемые volumes
echo "Удаление неиспользуемых volumes..."
docker volume prune -f

# Удалить неиспользуемые сети
echo "Удаление неиспользуемых сетей..."
docker network prune -f

# Полная очистка (все неиспользуемые ресурсы)
echo "Полная очистка неиспользуемых ресурсов..."
docker system prune -a -f --volumes

# Показать освобожденное место
echo ""
echo "=== Статистика Docker ==="
docker system df

echo ""
echo "=== Очистка завершена ==="

